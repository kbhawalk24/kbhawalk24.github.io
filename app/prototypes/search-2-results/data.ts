// Dummy data for the local Search 2.0 build. Every name, count and date here
// is invented; nothing comes from a real catalog. The set is shaped to hit the
// edge cases the screen has to handle: temporary and deprecated assets, a
// missing description, unknown row counts and health, zero usage, a very long
// name, stale refresh and usage dates, and categories with no matches.

/** Fixed "today" so dates and the 120-day filters render the same on server and client. */
export const NOW = Date.UTC(2026, 10, 9)

export type Classification = 'INTERNAL' | 'RESTRICTED' | 'PUBLIC'
export type Health = { score: number } | null

type Common = {
  id: string
  name: string
  store: string
  schema: string
  description: string | null
  owner: string
  updated: string // ISO date of last refresh
  lastUsed: string | null // ISO date of last query, null when never queried
  inDataMap: boolean
  domain: string | null
  alsoAs: ('kafka' | 'cdc')[]
  temporary: boolean
  deprecated: boolean
  maturity: 0 | 1 | 2 | 3 | 4 | 5
}

export type TableAsset = Common & {
  kind: 'table'
  objectType: 'TABLE' | 'VIEW'
  objectId: number
  classification: Classification
  columns: number
  rows: number | null
  health: Health
  queries: number
  users: number
  lineage: { entities: number; upstream: number; tables: number; dashboards: number } | null
}

export type ColumnAsset = Common & {
  kind: 'column'
  table: string
  dataType: 'decimal' | 'string' | 'timestamp' | 'integer'
  joins: number
  profile: number | null // share of the column profiled, 0 to 1
  lineage: { entities: number; upstream: number; tables: number } | null
}

